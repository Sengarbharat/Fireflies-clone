"use client";

import { CheckSquare, Copy, ListTree, MessageCircleQuestion, RefreshCw, Sparkles } from "lucide-react";
import { useState } from "react";
import { useToast } from "@/components/providers/ToastProvider";
import { Button } from "@/components/ui/Button";
import { cn, formatTimestamp, relativeTime } from "@/lib/format";
import type { ActionItem, MeetingDetail } from "@/lib/types";
import { ActionItemsTab } from "./ActionItemsTab";
import { AskTab } from "./AskTab";

export type NotesTab = "summary" | "actions" | "outline" | "ask";

interface Props {
  meeting: MeetingDetail;
  currentMs: number;
  onJump: (ms: number) => void;
  onKeyword: (k: string) => void;
  onRegenerate: () => Promise<void>;
  onMutated: () => Promise<unknown>;
  tab: NotesTab;
  onTabChange: (t: NotesTab) => void;
}

const GENERATED_LABEL: Record<string, string> = {
  seed: "AI notes",
  rules: "Auto-generated notes",
  llm: "Generated by Claude",
};

function groupByAssignee(items: ActionItem[]): [string, ActionItem[]][] {
  const groups = new Map<string, ActionItem[]>();
  for (const a of items) {
    const key = a.assignee?.name ?? "Unassigned";
    groups.set(key, [...(groups.get(key) ?? []), a]);
  }
  // Unassigned last
  return [...groups.entries()].sort(([a], [b]) => Number(a === "Unassigned") - Number(b === "Unassigned"));
}

function summaryAsText(meeting: MeetingDetail): string {
  const s = meeting.summary;
  if (!s) return "";
  const lines = [meeting.title, "", "Overview", s.overview, ""];
  if (s.notes.length) lines.push("Notes", ...s.notes.map((n) => `- ${n}`), "");
  if (meeting.action_items.length) {
    lines.push("Action items");
    for (const [owner, items] of groupByAssignee(meeting.action_items)) {
      lines.push(owner, ...items.map((a) => `- ${a.text}`));
    }
    lines.push("");
  }
  if (s.keywords.length) lines.push(`Keywords: ${s.keywords.join(", ")}`);
  return lines.join("\n");
}

export function NotesPanel({ meeting, currentMs, onJump, onKeyword, onRegenerate, onMutated, tab, onTabChange }: Props) {
  const toast = useToast();
  const [regenerating, setRegenerating] = useState(false);
  const summary = meeting.summary;

  const copySummary = async () => {
    try {
      await navigator.clipboard.writeText(summaryAsText(meeting));
      toast.success("Summary copied to clipboard");
    } catch {
      toast.error("Couldn't access the clipboard");
    }
  };
  const activeChapter = [...meeting.chapters].reverse().find((c) => c.start_ms <= currentMs)?.id;

  const tabs: { id: NotesTab; label: string; icon: typeof Sparkles; count?: number }[] = [
    { id: "summary", label: "Summary", icon: Sparkles },
    { id: "actions", label: "Action items", icon: CheckSquare, count: meeting.action_items_open },
    { id: "outline", label: "Outline", icon: ListTree },
    { id: "ask", label: "Ask AI", icon: MessageCircleQuestion },
  ];

  return (
    <section className="flex h-full min-h-0 flex-col">
      <div className="flex items-center gap-1 overflow-x-auto border-b px-4 scrollbar-thin">
        {tabs.map((t) => (
          <button
            key={t.id}
            onClick={() => onTabChange(t.id)}
            className={cn(
              "relative flex shrink-0 items-center gap-1.5 px-2.5 py-3 text-sm font-medium transition-colors",
              tab === t.id ? "text-brand-700 dark:text-brand-300" : "text-muted hover:text-current",
            )}
          >
            <t.icon className="h-4 w-4" />
            {t.label}
            {!!t.count && (
              <span className="rounded-full bg-brand-100 px-1.5 text-[10px] font-semibold text-brand-700 dark:bg-brand-500/20 dark:text-brand-300">{t.count}</span>
            )}
            {tab === t.id && <span className="absolute inset-x-1 bottom-0 h-0.5 rounded-full bg-brand-600" />}
          </button>
        ))}
      </div>

      <div className="min-h-0 flex-1 overflow-y-auto px-5 py-5 scrollbar-thin">
        {tab === "summary" &&
          (summary ? (
            <div className="space-y-6">
              <div className="flex flex-wrap items-center justify-between gap-2">
                <div>
                  <h2 className="text-base font-semibold">General Summary</h2>
                  <span className="mt-1 inline-flex items-center gap-1.5 rounded-full bg-gradient-to-r from-brand-50 to-pink-50 px-2.5 py-0.5 text-[11px] font-medium text-brand-700 dark:from-brand-500/15 dark:to-pink-500/10 dark:text-brand-300">
                    <Sparkles className="h-3 w-3" /> {GENERATED_LABEL[summary.generated_by] ?? "AI notes"} &middot; {relativeTime(summary.generated_at)}
                  </span>
                </div>
                <div className="flex items-center gap-1">
                  <Button size="sm" variant="ghost" onClick={copySummary}>
                    <Copy className="h-3.5 w-3.5" /> Copy
                  </Button>
                  <Button
                    size="sm"
                    variant="ghost"
                    loading={regenerating}
                    onClick={async () => {
                      setRegenerating(true);
                      await onRegenerate();
                      setRegenerating(false);
                    }}
                  >
                    {!regenerating && <RefreshCw className="h-3.5 w-3.5" />} Regenerate
                  </Button>
                </div>
              </div>

              <div>
                <h3 className="mb-2 text-sm font-semibold">Overview</h3>
                <p className="text-sm leading-relaxed">{summary.overview}</p>
              </div>

              {summary.keywords.length > 0 && (
                <div>
                  <h3 className="mb-2 text-sm font-semibold">Keywords</h3>
                  <div className="flex flex-wrap gap-1.5">
                    {summary.keywords.map((k) => (
                      <button
                        key={k}
                        onClick={() => onKeyword(k)}
                        title="Find in transcript"
                        className="rounded-full border px-2.5 py-0.5 text-xs hover:border-brand-300 hover:bg-brand-50 hover:text-brand-700 dark:hover:bg-brand-500/10"
                      >
                        {k}
                      </button>
                    ))}
                  </div>
                </div>
              )}

              {summary.notes.length > 0 && (
                <div>
                  <h3 className="mb-2 text-sm font-semibold">Notes</h3>
                  <ul className="space-y-2">
                    {summary.notes.map((n, i) => (
                      <li key={i} className="flex gap-2.5 text-sm leading-relaxed">
                        <span className="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-brand-400" />
                        {n}
                      </li>
                    ))}
                  </ul>
                </div>
              )}

              {meeting.action_items.length > 0 && (
                <div>
                  <h3 className="mb-2 flex items-center justify-between text-sm font-semibold">
                    Action items
                    <button onClick={() => onTabChange("actions")} className="text-xs font-medium text-brand-600 hover:underline">
                      Manage
                    </button>
                  </h3>
                  {/* Grouped by owner, as in Fireflies' summary */}
                  <div className="space-y-3">
                    {groupByAssignee(meeting.action_items).map(([owner, items]) => (
                      <div key={owner}>
                        <p className="mb-1 text-sm font-semibold">{owner}</p>
                        <ul className="space-y-1">
                          {items.map((a) => (
                            <li key={a.id} className={cn("flex gap-2 text-sm leading-relaxed", a.completed && "text-muted line-through")}>
                              <CheckSquare className={cn("mt-1 h-3.5 w-3.5 shrink-0", a.completed ? "text-brand-500" : "text-muted")} />
                              <span>
                                {a.text}
                                {a.source_start_ms !== null && (
                                  <button
                                    onClick={() => onJump(a.source_start_ms!)}
                                    className="ml-1.5 font-mono text-[11px] text-brand-600 no-underline hover:underline"
                                  >
                                    ({formatTimestamp(a.source_start_ms)})
                                  </button>
                                )}
                              </span>
                            </li>
                          ))}
                        </ul>
                      </div>
                    ))}
                  </div>
                </div>
              )}
            </div>
          ) : (
            <div className="py-10 text-center">
              <p className="text-sm text-muted">No AI notes yet{meeting.segments.length ? "" : ". Add a transcript to generate them"}.</p>
              {meeting.segments.length > 0 && (
                <Button className="mt-3" variant="primary" size="sm" loading={regenerating} onClick={async () => {
                  setRegenerating(true);
                  await onRegenerate();
                  setRegenerating(false);
                }}>
                  <Sparkles className="h-3.5 w-3.5" /> Generate notes
                </Button>
              )}
            </div>
          ))}

        {tab === "actions" && <ActionItemsTab meeting={meeting} currentMs={currentMs} onMutated={onMutated} onJump={onJump} />}

        {tab === "outline" &&
          (meeting.chapters.length ? (
            <ol className="relative space-y-1 before:absolute before:bottom-4 before:left-[27px] before:top-4 before:w-px before:bg-[var(--border)]">
              {meeting.chapters.map((c) => (
                <li key={c.id}>
                  <button
                    onClick={() => onJump(c.start_ms)}
                    className={cn(
                      "relative flex w-full gap-3 rounded-xl px-2 py-2.5 text-left transition-colors",
                      c.id === activeChapter ? "bg-brand-50 dark:bg-brand-500/10" : "hover:bg-black/[0.025] dark:hover:bg-white/[0.03]",
                    )}
                  >
                    <span
                      className={cn(
                        "z-10 mt-0.5 shrink-0 rounded-md border bg-surface px-1.5 py-0.5 font-mono text-[10px]",
                        c.id === activeChapter && "border-brand-400 text-brand-700 dark:text-brand-300",
                      )}
                    >
                      {formatTimestamp(c.start_ms)}
                    </span>
                    <span>
                      <span className="block text-sm font-semibold">{c.title}</span>
                      {c.summary && <span className="mt-0.5 block text-xs leading-relaxed text-muted">{c.summary}</span>}
                    </span>
                  </button>
                </li>
              ))}
            </ol>
          ) : (
            <p className="py-10 text-center text-sm text-muted">No outline yet.</p>
          ))}

        {tab === "ask" && <AskTab meetingId={meeting.id} onJump={onJump} />}
      </div>
    </section>
  );
}
